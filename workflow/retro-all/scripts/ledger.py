#!/usr/bin/env python3
"""The retro findings ledger: one file per finding under <ledger>/findings/, findings.md is their index.

  ledger.py index                       rewrite findings.md from findings/F-<n>.md and print the next free id
  ledger.py new CATEGORY TITLE          claim the next free id and create its file (safe against a concurrent retro)
  ledger.py recheck DIR                 match each live finding's recheck-rg against the transcripts in DIR/pending.tsv
  ledger.py import OTHER                renumber another ledger's findings into this one and merge its sessions.tsv

The first command on a ledger whose findings.md still holds the finding blocks splits it into findings/.
"""
import argparse, json, os, re, sys

from digest import LEDGER, complete_lines, read_ledger, utf8_safe_stdout

STATUSES = ('open', 'in-progress', 'fixed', 'wontfix', 'watch')
CATEGORIES = ('skill', 'patch', 'correction', 'guardrail', 'navigation', 'tool-economy', 'information-access')
LIVE = ('open', 'in-progress', 'fixed', 'watch')   # statuses whose recurrence matters


def parse(path):
    body = open(path, encoding='utf-8-sig').read()
    m = re.match(r'#+ (F-(\d+)) (.+)', body)
    if not m:
        sys.exit(f'{path}: first line must be "# F-<n> <title>"')
    f = dict(id=m.group(1), n=int(m.group(2)), title=m.group(3).strip(), path=path)
    for k, v in re.findall(r'^([a-z-]+): (.*)$', body, re.M):
        f.setdefault(k, v.strip())   # the field block comes first; a `key: value` line in the notes cannot override it
    if f.get('status') not in STATUSES or f.get('category') not in CATEGORIES:
        sys.exit(f"{path}: status {f.get('status')!r} or category {f.get('category')!r} not in the ledger's lists")
    if f'{f["id"]}.md' != os.path.basename(path):
        sys.exit(f'{path}: file name must be {f["id"]}.md')
    return f


def load(ledger):
    d = os.path.join(ledger, 'findings')
    # An empty file is one a concurrent `new` has claimed but not yet written.
    paths = [os.path.join(d, n) for n in os.listdir(d) if n.endswith('.md')] if os.path.isdir(d) else []
    fs = [parse(p) for p in paths if os.path.getsize(p)]
    return sorted(fs, key=lambda f: f['n'])


def split(ledger):
    """Move the `## F-<n>` blocks of an old single-file findings.md into findings/F-<n>.md."""
    src, d = os.path.join(ledger, 'findings.md'), os.path.join(ledger, 'findings')
    if os.path.isdir(d) or not os.path.exists(src):
        return
    os.makedirs(d)
    for blk in re.split(r'^(?=## F-\d+ )', open(src, encoding='utf-8-sig').read(), flags=re.M)[1:]:
        n = re.match(r'## (F-\d+)', blk).group(1)
        with open(os.path.join(d, n + '.md'), 'w', encoding='utf-8', newline='\n') as w:
            w.write(blk[1:].rstrip() + '\n')   # '## F-n' -> '# F-n'


def index(args):
    split(args.ledger)
    fs = load(args.ledger)
    nxt = f"F-{fs[-1]['n'] + 1 if fs else 1}"
    cell = lambda s: s.replace('|', r'\|')
    rows = [f"| [{f['id']}](findings/{f['id']}.md) | {f['status']} | {f['category']} | {cell(f['title'])} |\n" for f in fs]
    with open(os.path.join(args.ledger, 'findings.md'), 'w', encoding='utf-8', newline='\n') as w:
        w.write('# Retro findings\n\nGenerated by `ledger.py index` from `findings/F-<n>.md`: edit those, then rerun it.\n'
                f'Next id: {nxt}\n\n| id | status | category | title |\n|---|---|---|---|\n')
        w.writelines(rows)
    print(f'{len(fs)} findings in {args.ledger}; next id {nxt}')


def claim(ledger, body):
    """Create findings/F-<n>.md for the next free n, exclusively, with body ('{id}' -> the id); returns the id."""
    split(ledger)
    d = os.path.join(ledger, 'findings')
    os.makedirs(d, exist_ok=True)
    n = max([f['n'] for f in load(ledger)] + [0]) + 1
    while True:
        try:
            fd = os.open(os.path.join(d, f'F-{n}.md'), os.O_CREAT | os.O_EXCL | os.O_WRONLY)
        except FileExistsError:
            n += 1
            continue
        with os.fdopen(fd, 'w', encoding='utf-8', newline='\n') as w:
            w.write(body.replace('{id}', f'F-{n}'))
        return f'F-{n}'


def new(args):
    fid = claim(args.ledger, f'# {{id}} {args.title}\nstatus: open\ncategory: {args.category}\nevidence: \nfix: -\nrecheck: \n')
    index(args)
    print(os.path.join(args.ledger, 'findings', fid + '.md'))


def import_(args):
    split(args.other)
    for f in load(args.other):
        body = open(f['path'], encoding='utf-8-sig').read().rstrip('\n')
        body = re.sub(r'^#+ F-\d+', '# {id}', body, count=1) + f"\nimported-from: {f['id']} in {args.other}\n"
        print(f"{f['id']} -> {claim(args.ledger, body)}: {f['title']}")
    rows = read_ledger(args.ledger)
    for sid, row in read_ledger(args.other).items():
        if sid not in rows or int(row[2]) > int(rows[sid][2]):
            rows[sid] = row
    p = os.path.join(args.ledger, 'sessions.tsv')
    with open(p + '.tmp', 'w', encoding='utf-8', newline='\n') as w:
        w.writelines('\t'.join(r) + '\n' for r in sorted(rows.values()))
    os.replace(p + '.tmp', p)
    index(args)
    # ponytail: an "F-<n>" written inside an imported finding's text keeps its old number; fix those by hand.
    print('# a finding recorded on both sides is now two: mark the later one wontfix, fix: duplicate of F-<n>')


def strings(o):
    if isinstance(o, str):
        yield o
    elif isinstance(o, dict):
        for v in o.values():
            yield from strings(v)
    elif isinstance(o, list):
        for v in o:
            yield from strings(v)


def recheck(args):
    live = []
    for f in load(args.ledger):
        if f['status'] in LIVE and f.get('recheck-rg'):
            try:
                live.append((f, re.compile(f['recheck-rg'])))
            except re.error as e:
                print(f"{f['id']}: recheck-rg does not compile ({e}); recheck it by hand")
    hits = {f['id']: [] for f, _ in live}
    for row in open(os.path.join(args.dir, 'pending.tsv'), encoding='utf-8'):
        sid, path, end, prev = (row.rstrip('\n').split('\t') + ['0'])[:4]
        try:
            _, lines = complete_lines(path, int(prev), int(end))   # exactly the span digest.py summarised
        except OSError as e:
            print(f'# {sid[:8]}: transcript unreadable from this side ({e.strerror}): {path}')
            continue
        for line in lines:
            try:
                j = json.loads(line)
            except ValueError:
                continue
            # A recurrence is something the agent did: match its tool-call inputs (commands, scripts, edits),
            # never tool output, user prompts or harness text, which quote the pattern without doing it.
            if not isinstance(j, dict) or j.get('type') != 'assistant':
                continue
            calls = [b.get('input') for b in (j.get('message') or {}).get('content') or []
                     if isinstance(b, dict) and b.get('type') == 'tool_use']
            for s in strings(calls):
                for f, rx in live:
                    m = rx.search(s)
                    if m and sid[:8] not in (h[0] for h in hits[f['id']]):
                        hits[f['id']].append((sid[:8], s[max(0, m.start() - 60):m.end() + 60].replace('\n', ' ')))
    for f, _ in live:
        for sid, snip in hits[f['id']]:
            print(f"{f['id']} ({f['status']}) {sid}: {snip}")
    print(f'# {sum(map(len, hits.values()))} hits over {len(live)} findings with recheck-rg; '
          f"{sum(1 for f in load(args.ledger) if f['status'] in LIVE and not f.get('recheck-rg'))} live findings need a manual recheck")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--ledger', default=LEDGER)
    sub = ap.add_subparsers(dest='cmd', required=True)
    sub.add_parser('index')
    p = sub.add_parser('new')
    p.add_argument('category', choices=CATEGORIES)
    p.add_argument('title')
    sub.add_parser('recheck').add_argument('dir')
    sub.add_parser('import').add_argument('other')
    args = ap.parse_args(argv)
    utf8_safe_stdout()
    {'index': index, 'new': new, 'recheck': recheck, 'import': import_}[args.cmd](args)


if __name__ == '__main__':
    sys.exit(main())
